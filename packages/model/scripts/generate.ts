import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  allFields,
  arcColumn,
  entities,
  globalRules,
  type Entity,
  type Field,
} from "../src/index";

const OUTPUT_DIR = join(import.meta.dir, "..", "generated");
const HEADER = "// GENERATED by packages/model/scripts/generate.ts. Do not edit.\n";

const snake = (value: string) =>
  value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const camel = (value: string) => value[0]!.toLowerCase() + value.slice(1);
const table = (entity: Entity) => snake(entity.name);
const enumConst = (entity: Entity, column: string) =>
  column === "visibility" ? "visibility" : `${camel(entity.name)}${column[0]!.toUpperCase()}${column.slice(1)}`;
const enumDbName = (entity: Entity, column: string) =>
  column === "visibility" ? "visibility" : `${table(entity)}_${snake(column)}`;

/** Orders entities so that referenced tables are declared first. */
function sorted(): Entity[] {
  const byName = new Map(entities.map((entity) => [entity.name, entity]));
  const seen = new Set<string>();
  const result: Entity[] = [];
  const visit = (entity: Entity, path: string[]) => {
    if (seen.has(entity.name)) return;
    if (path.includes(entity.name)) {
      throw new Error(`Reference cycle: ${[...path, entity.name].join(" -> ")}`);
    }
    for (const field of Object.values(allFields(entity))) {
      if (field.type === "ref" && field.to !== entity.name) {
        visit(byName.get(field.to)!, [...path, entity.name]);
      }
    }
    seen.add(entity.name);
    result.push(entity);
  };
  entities.forEach((entity) => visit(entity, []));
  return result;
}

function drizzleColumn(entity: Entity, name: string, field: Field): string {
  const column = snake(name);
  let code: string;
  switch (field.type) {
    case "text":
    case "url":
    case "language":
      code = `text("${column}")`;
      break;
    case "int":
      code = `integer("${column}")`;
      break;
    case "bigint":
      code = `bigint("${column}", { mode: "number" })`;
      break;
    case "float":
      code = `doublePrecision("${column}")`;
      break;
    case "timestamp":
      code = `timestamp("${column}", { withTimezone: true })`;
      break;
    case "json":
      code = `jsonb("${column}")`;
      break;
    case "enum":
      code = `${enumConst(entity, name)}("${column}")`;
      break;
    case "ref":
      code = `uuid("${column}")`;
      break;
  }
  if (!field.optional) code += ".notNull()";
  if (name === "visibility") code += `.default("private")`;
  if (field.unique) code += ".unique()";
  if (field.type === "ref" && !usesCompositeKey(entity, field)) {
    const target = camel(field.to);
    code += `.references((): AnyPgColumn => ${target}.id, { onDelete: "${field.onDelete}" })`;
  }
  return code;
}

const usesCompositeKey = (entity: Entity, field: Field) =>
  field.type === "ref" && field.sameOwner && !field.optional && entity.scope !== "root";

function drizzleTable(entity: Entity): string {
  const fields = allFields(entity);
  const name = table(entity);
  const columns = Object.entries(fields).map(
    ([key, field]) => `    ${key}: ${drizzleColumn(entity, key, field)},`,
  );
  const constraints: string[] = [];

  if (entity.scope !== "root") {
    constraints.push(`unique("${name}_id_owner_key").on(t.id, t.ownerId)`);
  }
  for (const [key, field] of Object.entries(fields)) {
    if (field.type === "ref" && usesCompositeKey(entity, field)) {
      const target = camel(field.to);
      constraints.push(
        `foreignKey({ name: "${name}_${snake(key)}_owner_fk", columns: [t.${key}, t.ownerId], foreignColumns: [${target}.id, ${target}.ownerId] }).onDelete("${field.onDelete}")`,
      );
    }
  }
  (entity.unique ?? []).forEach((columnsList) => {
    const suffix = columnsList.map(snake).join("_");
    const expanded = columnsList.flatMap((column) => {
      const definition = entity.arcs?.[column];
      return definition
        ? definition.targets.map((target) => arcColumn(column, target))
        : [column];
    });
    const nulls = expanded.some((column) => fields[column]?.optional) ? ".nullsNotDistinct()" : "";
    constraints.push(
      `unique("${name}_${suffix}_key").on(${expanded.map((column) => `t.${column}`).join(", ")})${nulls}`,
    );
  });
  for (const [arcName, definition] of Object.entries(entity.arcs ?? {})) {
    const args = definition.targets.map((target) => `\${t.${arcColumn(arcName, target)}}`).join(", ");
    constraints.push(`check("${name}_${arcName}_one", sql\`num_nonnulls(${args}) = 1\`)`);
  }

  const extras = constraints.length
    ? `,\n  (t) => [\n${constraints.map((item) => `    ${item},`).join("\n")}\n  ]`
    : "";
  return `export const ${camel(entity.name)} = pgTable(
  "${name}",
  {
    id: uuid("id").primaryKey().defaultRandom(),
${columns.join("\n")}
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  }${extras},
);`;
}

function generateDrizzle(): string {
  const enums = new Map<string, string>();
  for (const entity of entities) {
    for (const [key, field] of Object.entries(allFields(entity))) {
      if (field.type === "enum") {
        enums.set(
          enumConst(entity, key),
          `export const ${enumConst(entity, key)} = pgEnum("${enumDbName(entity, key)}", ${JSON.stringify(field.values)});`,
        );
      }
    }
  }
  return `${HEADER}import { sql } from "drizzle-orm";
import {
  bigint,
  check,
  doublePrecision,
  foreignKey,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
  type AnyPgColumn,
} from "drizzle-orm/pg-core";

${[...enums.values()].join("\n")}

${sorted().map(drizzleTable).join("\n\n")}
`;
}

function zodType(field: Field): string {
  switch (field.type) {
    case "text":
      return "z.string().min(1)";
    case "url":
      return "z.httpUrl()";
    case "language":
      return "language";
    case "int":
      return "z.int()";
    case "bigint":
      return "z.int().nonnegative()";
    case "float":
      return "z.number().finite()";
    case "timestamp":
      return "z.coerce.date()";
    case "json":
      return "z.json()";
    case "enum":
      return `z.enum(${JSON.stringify(field.values)})`;
    case "ref":
      return "z.uuid()";
  }
}

function generateSchemas(): string {
  const blocks = entities.map((entity) => {
    const fields = Object.entries(allFields(entity));
    const read = fields.map(
      ([key, field]) => `  ${key}: ${zodType(field)}${field.optional ? ".nullable()" : ""},`,
    );
    const create = fields
      .filter(([key]) => key !== "ownerId")
      .map(([key, field]) => {
        const optional = field.optional ? ".nullish()" : key === "visibility" ? ".default(\"private\")" : "";
        return `  ${key}: ${zodType(field)}${optional},`;
      });
    const ownerOnly = fields.filter(([, field]) => field.ownerOnly).map(([key]) => `${key}: true`);
    const refinements = Object.entries(entity.arcs ?? {}).map(([arcName, definition]) => {
      const keys = definition.targets.map((target) => `"${arcColumn(arcName, target)}"`).join(", ");
      return `\n  .refine((value) => exactlyOne(value, [${keys}]), { path: ["${arcName}"], error: "Set exactly one target" })`;
    });
    const name = entity.name;
    const hasPublic = entity.scope !== "personal";
    const publicSchema = hasPublic
      ? `export const ${name}PublicSchema = ${name}Schema${ownerOnly.length ? `.omit({ ${ownerOnly.join(", ")} })` : ""};\n`
      : "";
    const publicType = hasPublic
      ? `export type ${name}Public = z.infer<typeof ${name}PublicSchema>;\n`
      : "";
    return `export const ${name}Schema = z.object({
  id: z.uuid(),
${read.join("\n")}
  createdAt: z.coerce.date(),
  updatedAt: z.coerce.date(),
});
${publicSchema}export const ${name}CreateSchema = z.strictObject({
${create.join("\n")}
})${refinements.join("")};
export type ${name} = z.infer<typeof ${name}Schema>;
${publicType}export type ${name}Create = z.input<typeof ${name}CreateSchema>;`;
  });

  return `${HEADER}import { z } from "zod";

const language = z.string().refine((value) => {
  try {
    return Intl.getCanonicalLocales(value).length === 1;
  } catch {
    return false;
  }
}, "Expected a BCP 47 language tag");

const exactlyOne = (value: Record<string, unknown>, keys: readonly string[]) =>
  keys.filter((key) => value[key] !== null && value[key] !== undefined).length === 1;

${blocks.join("\n\n")}
`;
}

function fieldType(field: Field): string {
  if (field.type === "ref") return `→ ${field.to}`;
  if (field.type === "enum") return field.values.join(" \\| ");
  return field.type;
}

function generateDocs(): string {
  const relations = entities.flatMap((entity) =>
    Object.entries(allFields(entity)).flatMap(([key, field]) =>
      field.type === "ref" && key !== "ownerId"
        ? [`  ${field.to} ${field.optional ? "|o" : "||"}--o{ ${entity.name} : ${key}`]
        : [],
    ),
  );
  const groups = [...new Set(entities.map((entity) => entity.group))];
  const sections = groups.map((group) => {
    const body = entities.filter((entity) => entity.group === group).map((entity) => {
      const rows = Object.entries(allFields(entity)).map(([key, field]) => {
        const flags = [
          field.optional ? "optional" : "required",
          field.ownerOnly ? "owner-only" : "",
          field.type === "ref" && field.sameOwner ? "same owner" : "",
        ].filter(Boolean);
        return `| \`${key}\` | ${fieldType(field)} | ${flags.join(", ")} | ${field.description} |`;
      });
      const invariants = (entity.invariants ?? []).map((rule) => `- ${rule}`).join("\n");
      const arcs = Object.keys(entity.arcs ?? {}).map(
        (name) => `- Exactly one \`${name}*Id\` column must be set.`,
      );
      const rules = [...arcs, invariants].filter(Boolean).join("\n");
      return `### ${entity.name}\n\n${entity.description} Scope: ${entity.scope}.\n\n| Field | Type | Constraints | Description |\n| --- | --- | --- | --- |\n${rows.join("\n")}${rules ? `\n\n${rules}` : ""}`;
    });
    return `## ${group}\n\n${body.join("\n\n")}`;
  });

  return `<!-- GENERATED by packages/model/scripts/generate.ts. Edit packages/model/src/entities instead. -->

# disnostos data model

Every entity also has \`id\`, \`createdAt\`, and \`updatedAt\`.

## Global rules

${globalRules.map((rule) => `- ${rule}`).join("\n")}

## Relationships

\`\`\`mermaid
erDiagram
${relations.join("\n")}
\`\`\`

${sections.join("\n\n")}
`;
}

export const outputs = (): Record<string, string> => ({
  "drizzle.ts": generateDrizzle(),
  "schemas.ts": generateSchemas(),
  "data-model.md": generateDocs(),
});

export const isCurrent = (): boolean =>
  Object.entries(outputs()).every(([file, content]) => {
    try {
      return readFileSync(join(OUTPUT_DIR, file), "utf8") === content;
    } catch {
      return false;
    }
  });

if (import.meta.main) {
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const [file, content] of Object.entries(outputs())) {
    writeFileSync(join(OUTPUT_DIR, file), content);
  }
}
