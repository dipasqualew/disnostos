import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  allFields,
  arcColumn,
  entities,
  globalRules,
  type Entity,
  type Field,
} from "../src/index";

const OUTPUT_DIR = join(import.meta.dir, "..", "generated");
const HEADER = "// GENERATED by packages/model/scripts/generate.ts. Do not edit.\n";

const snake = (value: string) =>
  value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const camel = (value: string) => value[0]!.toLowerCase() + value.slice(1);
const table = (entity: Entity) => snake(entity.name);
const enumConst = (entity: Entity, column: string) =>
  column === "visibility" ? "visibility" : `${camel(entity.name)}${column[0]!.toUpperCase()}${column.slice(1)}`;
const enumDbName = (entity: Entity, column: string) =>
  column === "visibility" ? "visibility" : `${table(entity)}_${snake(column)}`;

const TIMESTAMP_FIELDS = ["createdAt", "updatedAt"];

function generateFirestore(): string {
  const names = entities.map((entity) => `  ${entity.name}: "${table(entity)}",`);
  const converters = entities.map((entity) => {
    const fields = Object.entries(allFields(entity));
    const timestamps = [
      ...fields.filter(([, field]) => field.type === "timestamp").map(([key]) => key),
      ...TIMESTAMP_FIELDS,
    ];
    const optional = fields.filter(([, field]) => field.optional).map(([key]) => key);
    return `  ${entity.name}: converter(schemas.${entity.name}Schema, ${JSON.stringify(timestamps)}, ${JSON.stringify(optional)}),`;
  });
  return `${HEADER}import * as schemas from "./schemas";

/** Top-level Firestore collection of each entity. */
export const collections = {
${names.join("\n")}
} as const;

interface Snapshot {
  id: string;
  data(): Record<string, unknown>;
}

const toDate = (value: unknown) =>
  typeof (value as { toDate?: unknown } | null)?.toDate === "function"
    ? (value as { toDate(): Date }).toDate()
    : value;

/** Stores absent optional fields as null, and validates every document it reads. */
function converter<T extends { id: string }>(
  schema: { parse(value: unknown): T },
  timestamps: readonly string[],
  optional: readonly string[],
) {
  return {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    toFirestore(value: any): Record<string, unknown> {
      const { id: _id, ...data } = value as Record<string, unknown>;
      for (const key of optional) data[key] ??= null;
      return data;
    },
    fromFirestore(snapshot: Snapshot): T {
      const data: Record<string, unknown> = { ...snapshot.data(), id: snapshot.id };
      for (const key of optional) data[key] ??= null;
      for (const key of timestamps) data[key] = toDate(data[key]);
      return schema.parse(data);
    },
  };
}

export const converters = {
${converters.join("\n")}
};
`;
}

/** Firestore composite indexes, read by Terraform. */
function generateIndexes(): string {
  const indexes = entities.flatMap((entity) =>
    (entity.indexes ?? []).map((fields) => ({
      collection: table(entity),
      fields: [
        { field: "ownerId", order: "ASCENDING" },
        ...fields.map(({ field, order }) => ({
          field,
          order: order === "asc" ? "ASCENDING" : "DESCENDING",
        })),
      ],
    })),
  );
  return `${JSON.stringify({ indexes }, null, 2)}\n`;
}

function zodType(field: Field): string {
  switch (field.type) {
    case "text":
      return "z.string().min(1)";
    case "url":
      return "z.httpUrl()";
    case "language":
      return "language";
    case "int":
      return "z.int()";
    case "bigint":
      return "z.int().nonnegative()";
    case "float":
      return "z.number().finite()";
    case "timestamp":
      return "z.coerce.date()";
    case "date":
      return "calendarDate";
    case "json":
      return "z.json()";
    case "enum":
      return `z.enum(${JSON.stringify(field.values)})`;
    case "ref":
      return field.to === "User" ? "userId" : "z.uuid()";
  }
}

function generateSchemas(): string {
  const blocks = entities.map((entity) => {
    const fields = Object.entries(allFields(entity));
    const read = fields.map(
      ([key, field]) => `  ${key}: ${zodType(field)}${field.optional ? ".nullable()" : ""},`,
    );
    const create = fields
      .filter(([key]) => key !== "ownerId")
      .map(([key, field]) => {
        const optional = field.optional ? ".nullish()" : key === "visibility" ? ".default(\"private\")" : "";
        return `  ${key}: ${zodType(field)}${optional},`;
      });
    const ownerOnly = fields.filter(([, field]) => field.ownerOnly).map(([key]) => `${key}: true`);
    const refinements = Object.entries(entity.arcs ?? {}).map(([arcName, definition]) => {
      const keys = definition.targets.map((target) => `"${arcColumn(arcName, target)}"`).join(", ");
      return `\n  .refine((value) => exactlyOne(value, [${keys}]), { path: ["${arcName}"], error: "Set exactly one target" })`;
    });
    const name = entity.name;
    const hasPublic = entity.scope !== "personal";
    const publicSchema = hasPublic
      ? `export const ${name}PublicSchema = ${name}Schema${ownerOnly.length ? `.omit({ ${ownerOnly.join(", ")} })` : ""};\n`
      : "";
    const publicType = hasPublic
      ? `export type ${name}Public = z.infer<typeof ${name}PublicSchema>;\n`
      : "";
    return `export const ${name}Schema = z.object({
  id: ${entity.scope === "root" ? "userId" : "z.uuid()"},
${read.join("\n")}
  createdAt: z.coerce.date(),
  updatedAt: z.coerce.date(),
});
${publicSchema}export const ${name}CreateSchema = z.strictObject({
${create.join("\n")}
})${refinements.join("")};
export type ${name} = z.infer<typeof ${name}Schema>;
${publicType}export type ${name}Create = z.input<typeof ${name}CreateSchema>;`;
  });

  return `${HEADER}import { z } from "zod";

const language = z.string().refine((value) => {
  try {
    return Intl.getCanonicalLocales(value).length === 1;
  } catch {
    return false;
  }
}, "Expected a BCP 47 language tag");

/** Identity Platform user IDs are opaque strings, not UUIDs. */
const userId = z.string().min(1).max(128);

/** A real calendar day as YYYY-MM-DD, with no time or timezone. */
const calendarDate = z.string().refine((value) => {
  if (!/^\\d{4}-\\d{2}-\\d{2}$/.test(value)) return false;
  const date = new Date(\`\${value}T00:00:00.000Z\`);
  return !Number.isNaN(date.getTime()) && date.toISOString().startsWith(value);
}, "Expected a calendar date as YYYY-MM-DD");

const exactlyOne = (value: Record<string, unknown>, keys: readonly string[]) =>
  keys.filter((key) => value[key] !== null && value[key] !== undefined).length === 1;

${blocks.join("\n\n")}
`;
}

function fieldType(field: Field): string {
  if (field.type === "ref") return `→ ${field.to}`;
  if (field.type === "enum") return field.values.join(" \\| ");
  return field.type;
}

function generateDocs(): string {
  const relations = entities.flatMap((entity) =>
    Object.entries(allFields(entity)).flatMap(([key, field]) =>
      field.type === "ref" && key !== "ownerId"
        ? [`  ${field.to} ${field.optional ? "|o" : "||"}--o{ ${entity.name} : ${key}`]
        : [],
    ),
  );
  const groups = [...new Set(entities.map((entity) => entity.group))];
  const sections = groups.map((group) => {
    const body = entities.filter((entity) => entity.group === group).map((entity) => {
      const rows = Object.entries(allFields(entity)).map(([key, field]) => {
        const flags = [
          field.optional ? "optional" : "required",
          field.ownerOnly ? "owner-only" : "",
          field.type === "ref" && field.sameOwner ? "same owner" : "",
          field.type === "ref" && field.onDelete === "keep" ? "kept when target is deleted" : "",
        ].filter(Boolean);
        return `| \`${key}\` | ${fieldType(field)} | ${flags.join(", ")} | ${field.description} |`;
      });
      const invariants = (entity.invariants ?? []).map((rule) => `- ${rule}`).join("\n");
      const arcs = Object.keys(entity.arcs ?? {}).map(
        (name) => `- Exactly one \`${name}*Id\` field must be set.`,
      );
      const rules = [...arcs, invariants].filter(Boolean).join("\n");
      return `### ${entity.name}\n\n${entity.description} Scope: ${entity.scope}.\n\n| Field | Type | Constraints | Description |\n| --- | --- | --- | --- |\n${rows.join("\n")}${rules ? `\n\n${rules}` : ""}`;
    });
    return `## ${group}\n\n${body.join("\n\n")}`;
  });

  return `<!-- GENERATED by packages/model/scripts/generate.ts. Edit packages/model/src/entities instead. -->

# disnostos data model

Every entity also has \`id\`, \`createdAt\`, and \`updatedAt\`.

## Global rules

${globalRules.map((rule) => `- ${rule}`).join("\n")}

## Relationships

\`\`\`mermaid
erDiagram
${relations.join("\n")}
\`\`\`

${sections.join("\n\n")}
`;
}

export const outputs = (): Record<string, string> => ({
  "firestore.ts": generateFirestore(),
  "firestore.indexes.json": generateIndexes(),
  "schemas.ts": generateSchemas(),
  "data-model.md": generateDocs(),
});

export const isCurrent = (): boolean =>
  Object.entries(outputs()).every(([file, content]) => {
    try {
      return readFileSync(join(OUTPUT_DIR, file), "utf8") === content;
    } catch {
      return false;
    }
  });

if (import.meta.main) {
  mkdirSync(OUTPUT_DIR, { recursive: true });
  for (const [file, content] of Object.entries(outputs())) {
    writeFileSync(join(OUTPUT_DIR, file), content);
  }
}
